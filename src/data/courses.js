// ---------- Selectors ----------

export const getPopularCourses = () =>
  [...courses].sort((a, b) => b.rating - a.rating).slice(0, 3);

export const getTrendingCourses = () =>
  courses.filter((c) => c.trending).slice(0, 6);

export const getCourseById = (id) =>
  courses.find((c) => String(c.id) === String(id));

export const getCategories = () => [...new Set(courses.map((c) => c.category))];
